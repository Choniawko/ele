const start = (id: string, label = "START"): Device => ({
  id,
  kind: "button",
  label,
});
const stop = (id: string, label = "STOP"): Device => ({
  id,
  kind: "button",
  label,
});
const latch = (id: string, label = "wyłącznik"): Device => ({
  id,
  kind: "button",
  label,
  latching: true,
});
const K = (id: string, label?: string): Device => ({
  id,
  kind: "contactor",
  label,
});
const TON = (id: string, s: number): Device => ({
  id,
  kind: "timer-on",
  delayMs: s * 1000,
});
const TOF = (id: string, s: number): Device => ({
  id,
  kind: "timer-off",
  delayMs: s * 1000,
});
const H = (id: string, color: LampColor = "yellow", label?: string): Device => ({
  id,
  kind: "lamp",
  color,
  label,
});
const sensorOut = (device: string): ContactElement => ({
  kind: "contact",
  device,
  type: "no",
  terminals: ["BN", "BK"],
});
const tap = (id: string) => ({ tap: id });
const hold = (id: string) => ({ hold: id });
const release = (id: string) => ({ release: id });
const toggle = (id: string) => ({ toggle: id });
const wait = (s: number) => ({ wait: s * 1000 });

